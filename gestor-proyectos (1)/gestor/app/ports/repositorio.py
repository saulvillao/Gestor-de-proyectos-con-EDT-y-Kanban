"""Contrato mínimo de persistencia. Todo devuelve Ok(...) o Err(ErrorPersistencia...)."""
from typing import Protocol

from app.domain.models import Integrante, Paquete, Proyecto, Tarea
from app.domain.result import Err, Ok


class Repositorio(Protocol):
    def guardar_proyecto(self, p: Proyecto) -> Ok | Err: ...
    def listar_proyectos(self) -> Ok | Err: ...
    def guardar_integrante(self, i: Integrante) -> Ok | Err: ...
    def listar_integrantes(self, proyecto_id: int) -> Ok | Err: ...
    def guardar_paquete(self, p: Paquete) -> Ok | Err: ...
    def listar_paquetes(self, proyecto_id: int) -> Ok | Err: ...
    def guardar_tarea(self, t: Tarea) -> Ok | Err: ...
    def listar_tareas(self, proyecto_id: int) -> Ok | Err: ...
